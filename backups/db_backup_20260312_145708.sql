        CASE
            WHEN ((ip.payment_status)::text = 'Pending'::text) THEN ip.net_payable
            ELSE (0)::numeric
        END) AS pending_amount
   FROM (public.companies c
     LEFT JOIN public.interest_payables ip ON ((c.company_id = ip.company_id)))
  GROUP BY c.company_id, c.company_code, c.company_name, c.sector_type;


