CREATE VIEW public.vw_client_payables_summary AS
 SELECT cl.client_id,
    cl.client_code,
    cl.full_name,
    cl.holder_type,
    count(DISTINCT ip.interest_id) AS interest_count,
    count(DISTINCT dp.dividend_id) AS dividend_count,
    COALESCE(sum(ip.net_payable), (0)::numeric) AS total_interest,
    COALESCE(sum(dp.net_payable), (0)::numeric) AS total_dividend,
    (COALESCE(sum(ip.net_payable), (0)::numeric) + COALESCE(sum(dp.net_payable), (0)::numeric)) AS total_payable
   FROM ((public.clients cl
     LEFT JOIN public.interest_payables ip ON ((cl.client_id = ip.client_id)))
     LEFT JOIN public.dividend_payables dp ON ((cl.client_id = dp.client_id)))
  GROUP BY cl.client_id, cl.client_code, cl.full_name, cl.holder_type;


