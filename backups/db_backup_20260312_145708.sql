--
-- Name: vw_dividend_summary_by_company; Type: VIEW; Schema: public; Owner: rta_user
--

CREATE VIEW public.vw_dividend_summary_by_company AS
 SELECT c.company_id,
    c.company_code,
    c.company_name,
    count(dp.dividend_id) AS total_records,
    sum(dp.shares_held) AS total_shares,
    sum(dp.gross_dividend) AS total_gross,
    sum(dp.tax_amount) AS total_tax,
    sum(dp.net_payable) AS total_net,
    sum(
        CASE
            WHEN ((dp.payment_status)::text = 'Paid'::text) THEN dp.net_payable
            ELSE (0)::numeric
        END) AS paid_amount,
    sum(
        CASE
            WHEN ((dp.payment_status)::text = 'Pending'::text) THEN dp.net_payable
            ELSE (0)::numeric
        END) AS pending_amount
   FROM (public.companies c
